"""``SKILL.md``: the agent skill of a profile, generated from the live server.

Generated, then extended: the connection, the sign-in rule and the tool table
come from the running server so they cannot drift from it; what the project adds
(``MCPSkillConfig.sections``) follows. Only an explicit ``file`` replaces it.

**What a caller who is not signed in may read** is the same as ``/info/`` allows
before authentication: the name and the URL. The tool table and the server's
``instructions`` are a capability map, so they appear only when the request
carries a credential this profile accepts.
"""

from __future__ import annotations

import json
import logging
import re
from pathlib import Path
from typing import Any, Iterable, Optional

from django_cfg.modules.django_mcp.__cfg__ import MCPSkillConfig

from .script import clean_name

logger = logging.getLogger(__name__)

CONTENT_TYPE = "text/markdown; charset=utf-8"
#: ``install.sh --uninstall`` removes a skill file only when it carries this line.
MARKER = "<!-- generated by django-cfg -->"

#: Profiles that take the bare alias; every other one is ``<alias>-<profile>`` so
#: an operator surface never replaces the public one in a client.
_BARE_PROFILES = ("default", "public")


def slugify_alias(text: str) -> str:
    slug = re.sub(r"[^a-z0-9_-]+", "-", (text or "").lower()).strip("-_")[:32].strip("-_")
    return slug or "mcp"


def effective_skill(config: Any, profile: Any) -> MCPSkillConfig:
    return getattr(profile, "skill", None) or getattr(config, "skill", None) or MCPSkillConfig()


def resolve_alias(config: Any, profile: Any, server_name: str) -> str:
    skill = effective_skill(config, profile)
    if skill.alias:
        return skill.alias
    base = slugify_alias(server_name)
    profile_name = getattr(profile, "name", None) or "default"
    if profile_name in _BARE_PROFILES:
        return base
    return slugify_alias(f"{base}-{profile_name}")


def default_description(name: str) -> str:
    return f"Use when the user wants to work with {name} through its MCP server: connect it, then call its tools."


def read_skill_file(skill: MCPSkillConfig) -> Optional[str]:
    """The hand-written file, or None (and an error in the log) when unusable."""
    if not skill.file:
        return None
    from django.conf import settings

    base = Path(getattr(settings, "BASE_DIR", ".")).resolve()
    path = (base / skill.file).resolve()
    try:
        path.relative_to(base)
        return path.read_text(encoding="utf-8")
    except (ValueError, OSError) as exc:
        logger.error("MCP skill file %r is unusable (%s); serving the generated skill", skill.file, exc)
        return None


def _line(text: str) -> str:
    return re.sub(r"\s+", " ", text or "").strip()


def _cell(text: str, limit: int = 200) -> str:
    first = _line((text or "").strip().split("\n\n")[0])
    if len(first) > limit:
        first = first[: limit - 1].rstrip() + "…"
    return first.replace("|", "\\|")


def render_skill(
    *,
    alias: str,
    name: str,
    url: str,
    oauth: bool,
    skill: MCPSkillConfig,
    tools: Optional[Iterable[Any]] = None,
    instructions: Optional[str] = None,
    file_text: Optional[str] = None,
) -> str:
    """The skill text. ``tools`` / ``instructions`` are None for an anonymous caller."""
    if file_text is not None:
        return file_text

    name = clean_name(name, alias)
    description = _line(skill.description or "") or default_description(name)
    out = [
        "---",
        f"name: {alias}",
        # JSON string = a valid YAML double-quoted scalar, whatever the text holds.
        f"description: {json.dumps(description, ensure_ascii=False)}",
        "---",
        MARKER,
        "",
        f"# {name}",
        "",
        "## Connect",
        "",
        f"The MCP server is at `{url}`. To connect Claude Code, Codex and Gemini CLI in one step:",
        "",
        "```sh",
        f"curl -fsSL {url}install.sh | sh",
        "```",
        "",
        f"By hand in Claude Code: `claude mcp add --scope user --transport http {alias} {url}`"
        + ("" if oauth else " --header \"X-MCP-Access-Key: $MCP_API_KEY\""),
        "",
        "## Authorization",
        "",
    ]
    if oauth:
        out.append("The server signs the person in on first use (OAuth). The person confirms the sign-in in their browser.")
    else:
        out.append(
            "The server needs the person's API key, sent as `X-MCP-Access-Key`. "
            "The installer reads it from the `MCP_API_KEY` environment variable or asks for it without echo."
        )
    out += [
        "",
        "- Never ask the person to paste an API key or a token into the chat.",
        "- Never print a key, and never write it into a file in a project.",
        "- A sign-in is confirmed by the person, not by you.",
        "",
        "## Tools",
        "",
    ]
    if tools is None:
        out.append("Call `tools/list` after connecting: the server answers with its current tools.")
    else:
        rows = sorted(tools, key=lambda t: t.name)
        out += ["| Tool | What it does |", "| --- | --- |"]
        out += [f"| `{t.name}` | {_cell(t.description)} |" for t in rows]
    if instructions:
        out += ["", "## Server instructions", "", instructions.strip()]
    for title, body in skill.sections.items():
        out += ["", f"## {_line(title)}", "", body.strip()]
    return "\n".join(out) + "\n"
