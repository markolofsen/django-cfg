"""Typed stream wrappers for ``text/event-stream`` operations.

Hey API already emits an SDK method for an SSE operation that returns
``{ stream: AsyncGenerator<Frame> }`` (the union comes from the 200 schema, e.g.
a ``oneOf`` discriminated by ``type``). Used raw it has three traps for a
request/response API that answers refusals before the stream starts:

  * it RETRIES forever by default (``sseMaxRetryAttempts`` unset), so a 409 or
    429 is re-sent with growing back-off instead of surfacing;
  * a non-2xx answer becomes ``new Error("SSE failed: 409 Conflict")``, the
    problem body and ``Retry-After`` are lost, and the type of the error is
    ``unknown``;
  * a network failure ends the loop silently (``onSseError`` only).

``streams.ts`` (one per group, only when the group has an SSE operation) adds
one function per such operation, ``stream<OperationId>(options)``: the same
options as the SDK method, an ``AsyncGenerator<Frame>`` back, no retry (the
caller decides: the server may not resume by event id), a typed
``StreamHttpError`` for a refusal and for a lost connection. No new dialect and
no runtime beyond what is emitted here.
"""

from __future__ import annotations

from pathlib import Path

from ..hooks.sdk_names import _hey_api_pascal, sdk_class_name, sdk_fn_name, sdk_type_names
from ..ir import IR, IROperation

STREAMS_FILE = "streams.ts"

_HEADER = """// AUTO-GENERATED by openapi_processor / ts.streams
// Typed wrappers for text/event-stream operations. DO NOT EDIT — re-run `make gen`.
//
//   for await (const frame of streamXxx({ path, body, signal })) {
//     switch (frame.type) { ... }          // narrows on the schema's discriminator
//   }
//
// A refusal before the stream (4xx/5xx) and a lost connection throw
// StreamHttpError / the underlying error AFTER the frames already received;
// nothing is retried. An aborted `signal` ends the loop without an error.

"""

_RUNTIME = """/** A non-2xx answer to a stream request. `problem` is the parsed JSON body (typed per operation). */
export class StreamHttpError<TProblem = unknown> extends Error {
  readonly status: number;
  readonly problem: TProblem | undefined;
  /** Seconds, from the `Retry-After` header when it is a number. */
  readonly retryAfter: number | undefined;

  constructor(status: number, statusText: string, problem: TProblem | undefined, retryAfter: number | undefined) {
    super(`stream failed: ${status} ${statusText}`.trim());
    this.name = 'StreamHttpError';
    this.status = status;
    this.problem = problem;
    this.retryAfter = retryAfter;
  }
}

async function toStreamHttpError<TProblem>(response: Response): Promise<StreamHttpError<TProblem>> {
  let problem: TProblem | undefined;
  try {
    const type = response.headers.get('content-type') ?? '';
    if (type.includes('json')) problem = (await response.json()) as TProblem;
  } catch {
    problem = undefined;
  }
  const raw = Number(response.headers.get('retry-after'));
  return new StreamHttpError<TProblem>(
    response.status,
    response.statusText,
    problem,
    Number.isFinite(raw) && raw >= 0 ? raw : undefined,
  );
}
"""


def _is_sse(op: IROperation) -> bool:
    return any(m.startswith("text/event-stream") for m in op.response_media_types)


def sse_operations(ir: IR) -> list[IROperation]:
    return [op for op in ir.operations if op.has_2xx_response and _is_sse(op)]


def stream_fn_name(op: IROperation) -> str:
    return "stream" + _hey_api_pascal(op.operation_id)


def _render_op(op: IROperation) -> str:
    cls = sdk_class_name(op)
    method = sdk_fn_name(op)
    data, responses = sdk_type_names(op)
    pascal = data.removesuffix("Data")
    errors = f"{pascal}Errors"
    problem = f"{errors}[keyof {errors}]" if op.has_error_responses else "unknown"
    frame = f"{responses}[keyof {responses}]"
    name = stream_fn_name(op)
    return f"""
/** {op.method.upper()} {op.path} — frames of the 200 `text/event-stream` answer. */
export type {pascal}Frame = {frame};
export type {pascal}StreamError = StreamHttpError<{problem}>;

export async function* {name}(
  options: Options<{data}, false, {pascal}Response>,
): AsyncGenerator<{pascal}Frame, void, unknown> {{
  let failure: unknown;
  const baseFetch = options.fetch ?? globalThis.fetch;
  const {{ stream }} = await {cls}.{method}({{
    ...options,
    sseMaxRetryAttempts: 1,
    fetch: async (input: RequestInfo | URL, init?: RequestInit) => {{
      const response = await baseFetch(input, init);
      if (!response.ok) {{
        failure = await toStreamHttpError<{problem}>(response);
        throw failure;
      }}
      return response;
    }},
    onSseError: (error: unknown) => {{
      failure ??= error;
      options.onSseError?.(error);
    }},
  }});
  for await (const frame of stream) yield frame as {pascal}Frame;
  if (failure !== undefined && !options.signal?.aborted) throw failure;
}}
"""


def render_streams(ops: list[IROperation], *, sdk_import_prefix: str) -> str:
    classes = sorted({sdk_class_name(op) for op in ops})
    type_names: set[str] = set()
    for op in ops:
        data, responses = sdk_type_names(op)
        pascal = data.removesuffix("Data")
        type_names.update({data, responses, f"{pascal}Response"})
        if op.has_error_responses:
            type_names.add(f"{pascal}Errors")
    lines = [
        _HEADER,
        f"import {{ {', '.join(classes)}, type Options }} from '{sdk_import_prefix}/sdk.gen';",
        f"import type {{ {', '.join(sorted(type_names))} }} from '{sdk_import_prefix}/types.gen';",
        "",
        _RUNTIME,
    ]
    lines.extend(_render_op(op) for op in sorted(ops, key=lambda o: o.operation_id))
    return "\n".join(lines)


def generate_streams(ir: IR, out_dir: Path, *, sdk_import_prefix: str = "..") -> list[Path]:
    """Write ``out_dir/streams.ts`` when the IR has an SSE operation; remove a stale one otherwise.

    ``sdk_import_prefix`` is the path from ``out_dir`` to the real hey-api SDK:
    ``".."`` per-group (``target_root/_<group>/``), ``"."`` flat.
    """
    path = out_dir / STREAMS_FILE
    ops = sse_operations(ir)
    if not ops:
        path.unlink(missing_ok=True)
        return []
    out_dir.mkdir(parents=True, exist_ok=True)
    path.write_text(render_streams(ops, sdk_import_prefix=sdk_import_prefix), encoding="utf-8")
    return [path]
