"""Rust wrapper generator — post-processes progenitor output.

progenitor's ``Client::new_with_client(baseurl, reqwest::Client)`` leaves the
caller to assemble the base URL and the auth headers. This writes
``src/django.rs`` into the crate and exports it from ``lib.rs``::

    let api = my_api::DjangoClientBuilder::new()   // base URL from MY_API_BASE_URL
        .token(jwt)                                 // Authorization: Bearer …
        .build()?;
    let me = api.cfg_accounts_profile_retrieve().send().await?;

Idempotent: re-running rewrites ``django.rs`` and adds the ``lib.rs`` lines once. Last, ``rustfmt`` formats
``src/*.rs`` as ``cargo fmt`` would (``format_crate``), so a formatted workspace shows no drift after ``make gen``.
"""

from __future__ import annotations

import inspect
import json
import os
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

import tomllib

_LIB_MARKER = "// django-cfg: DjangoClientBuilder"


@dataclass(slots=True)
class RustWrapperResult:
    out_dir: Path
    written: list[Path] = field(default_factory=list)
    skipped: bool = False
    #: Dependencies the workspace root does not declare yet (see ``workspace-dependencies.toml``).
    missing_workspace_deps: list[str] = field(default_factory=list)
    #: ``False`` when rustfmt was not found or failed: the crate is written but not formatted.
    formatted: bool = True


def env_var_for(crate_name: str) -> str:
    """``djangocfg-api`` → ``DJANGOCFG_API_BASE_URL``."""
    return re.sub(r"[^A-Z0-9]+", "_", crate_name.upper()).strip("_") + "_BASE_URL"


def _crate_name(out_dir: Path) -> str:
    cargo = out_dir / "Cargo.toml"
    if cargo.is_file():
        m = re.search(r'^name\s*=\s*"([^"]+)"', cargo.read_text(encoding="utf-8"), re.MULTILINE)
        if m:
            return m.group(1)
    return out_dir.name


def render(crate_name: str) -> str:
    env = env_var_for(crate_name)
    return f'''// Code generated by django-cfg (openapi_processor.rust) — DO NOT EDIT.
// Regenerated on every `make gen`.

//! [`DjangoClientBuilder`]: the configured way into this crate's [`Client`](crate::Client).
//!
//! ```no_run
//! # async fn demo() -> Result<(), Box<dyn std::error::Error>> {{
//! let api = {crate_name.replace("-", "_")}::DjangoClientBuilder::new()
//!     .base_url("https://api.example.com") // or set {env}
//!     .token("<jwt>")
//!     .build()?;
//! # let _ = api;
//! # Ok(()) }}
//! ```

use reqwest::header::{{HeaderMap, HeaderValue, AUTHORIZATION}};

/// Environment variable consulted when no base URL is given to the builder.
pub const BASE_URL_ENV: &str = "{env}";

/// Why a [`DjangoClientBuilder`] could not build a client.
#[derive(Debug)]
pub enum DjangoClientError {{
    /// Neither [`DjangoClientBuilder::base_url`] nor `{env}` gave a URL.
    MissingBaseUrl,
    /// The token or API key holds characters an HTTP header cannot carry.
    InvalidHeader(&'static str),
    /// `reqwest` refused the client configuration.
    Http(reqwest::Error),
}}

impl std::fmt::Display for DjangoClientError {{
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {{
        match self {{
            Self::MissingBaseUrl => write!(f, "django client: base URL is required — call base_url() or set {env}"),
            Self::InvalidHeader(name) => write!(f, "django client: {{name}} is not a valid HTTP header value"),
            Self::Http(err) => write!(f, "django client: {{err}}"),
        }}
    }}
}}

impl std::error::Error for DjangoClientError {{
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {{
        match self {{
            Self::Http(err) => Some(err),
            _ => None,
        }}
    }}
}}

/// Builds a [`Client`](crate::Client) that talks to a django-cfg backend.
///
/// Base URL resolution: [`base_url`](Self::base_url), else the `{env}`
/// environment variable, else [`DjangoClientError::MissingBaseUrl`].
#[derive(Debug, Clone, Default)]
#[must_use]
pub struct DjangoClientBuilder {{
    base_url: Option<String>,
    token: Option<String>,
    api_key: Option<String>,
    headers: HeaderMap,
    #[cfg(not(target_arch = "wasm32"))]
    timeout: Option<std::time::Duration>,
}}

impl DjangoClientBuilder {{
    pub fn new() -> Self {{
        Self::default()
    }}

    /// The backend origin, e.g. `https://api.example.com` (a trailing `/` is dropped).
    pub fn base_url(mut self, url: impl Into<String>) -> Self {{
        self.base_url = Some(url.into());
        self
    }}

    /// JWT access token, sent as `Authorization: Bearer <token>`.
    pub fn token(mut self, token: impl Into<String>) -> Self {{
        self.token = Some(token.into());
        self
    }}

    /// API key, sent as the `X-Api-Key` header.
    pub fn api_key(mut self, key: impl Into<String>) -> Self {{
        self.api_key = Some(key.into());
        self
    }}

    /// One more header on every request (e.g. `Accept-Language`).
    pub fn header(mut self, name: reqwest::header::HeaderName, value: HeaderValue) -> Self {{
        self.headers.insert(name, value);
        self
    }}

    /// Whole-request timeout (connect + response).
    #[cfg(not(target_arch = "wasm32"))]
    pub fn timeout(mut self, timeout: std::time::Duration) -> Self {{
        self.timeout = Some(timeout);
        self
    }}

    /// The progenitor client, configured. A new token means a new client: build again.
    pub fn build(self) -> Result<crate::Client, DjangoClientError> {{
        let base_url = self
            .base_url
            .filter(|url| !url.trim().is_empty())
            .or_else(|| std::env::var(BASE_URL_ENV).ok().filter(|url| !url.trim().is_empty()))
            .ok_or(DjangoClientError::MissingBaseUrl)?;
        let base_url = base_url.trim().trim_end_matches('/').to_owned();

        let mut headers = self.headers;
        if let Some(token) = self.token {{
            let mut value = HeaderValue::from_str(&format!("Bearer {{token}}"))
                .map_err(|_| DjangoClientError::InvalidHeader("token"))?;
            value.set_sensitive(true);
            headers.insert(AUTHORIZATION, value);
        }}
        if let Some(key) = self.api_key {{
            let mut value = HeaderValue::from_str(&key).map_err(|_| DjangoClientError::InvalidHeader("api_key"))?;
            value.set_sensitive(true);
            headers.insert("x-api-key", value);
        }}

        let builder = reqwest::Client::builder().default_headers(headers);
        #[cfg(not(target_arch = "wasm32"))]
        let builder = match self.timeout {{
            Some(timeout) => builder.timeout(timeout),
            None => builder,
        }};
        let http = builder.build().map_err(DjangoClientError::Http)?;
        Ok(crate::Client::new_with_client(&base_url, http))
    }}
}}
'''


# ── multipart operations ─────────────────────────────────────────────

_METHODS = ("get", "put", "post", "delete", "options", "head", "patch", "trace")
_RUST_KEYWORDS = {
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in",
    "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self", "static", "struct", "super", "trait",
    "true", "type", "unsafe", "use", "where", "while", "async", "await", "dyn", "abstract", "become", "box", "do",
    "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen",
}


def _ident(name: str) -> str:
    ident = re.sub(r"[^0-9a-zA-Z_]+", "_", re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name)).strip("_").lower()
    if not ident or ident[0].isdigit():
        ident = f"p_{ident}"
    return f"r#{ident}" if ident in _RUST_KEYWORDS else ident


def _norm(name: str) -> str:
    return re.sub(r"[^0-9a-z]", "", name.lower())


def _rust_types(lib_text: str) -> dict[str, str]:
    """Normalized schema name → the Rust type typify gave it, read from the generated ``types`` module."""
    return {_norm(n): n for n in re.findall(r"^\s{4}pub (?:struct|enum|type) (\w+)", lib_text, re.MULTILINE)}


def _resolve(schema: dict, schemas: dict) -> dict:
    if "$ref" in schema:
        return schemas.get(schema["$ref"].rsplit("/", 1)[-1], {})
    if len(schema.get("allOf") or ()) == 1:
        return _resolve(schema["allOf"][0], schemas)
    return schema


def _doc(text: str) -> list[str]:
    return [f"    /// {line}".rstrip() for line in inspect.cleandoc(text).splitlines()]


def _render_multipart(path: str, method: str, op: dict, schemas: dict, types: dict[str, str]) -> str:
    name = _ident(op.get("operationId") or f"{method}_{path}")
    body = _resolve(op["requestBody"]["content"]["multipart/form-data"].get("schema") or {}, schemas)
    required = set(body.get("required") or ())

    args, parts = ["&self"], []
    path_params = re.findall(r"\{([^}]+)\}", path)
    for param in path_params:
        args.append(f"{_ident(param)}: &str")
    for field_name, prop in (body.get("properties") or {}).items():
        prop = _resolve(prop, schemas)
        ident = _ident(field_name)
        is_file = prop.get("format") == "binary"
        is_files = prop.get("type") == "array" and _resolve(prop.get("items") or {}, schemas).get("format") == "binary"
        if is_files:
            args.append(f"{ident}: Vec<reqwest::multipart::Part>")
            parts.append(f'    for part in {ident} {{\n        form = form.part("{field_name}", part);\n    }}')
        elif field_name in required:
            args.append(f"{ident}: {'reqwest::multipart::Part' if is_file else 'impl Into<String>'}")
            call = f'form.part("{field_name}", {ident})' if is_file else f'form.text("{field_name}", {ident}.into())'
            parts.append(f"    form = {call};")
        else:
            args.append(f"{ident}: Option<{'reqwest::multipart::Part' if is_file else 'String'}>")
            call = f'form.part("{field_name}", v)' if is_file else f'form.text("{field_name}", v)'
            parts.append(f"    if let Some(v) = {ident} {{\n        form = {call};\n    }}")

    success = "()"
    for code, response in sorted((op.get("responses") or {}).items()):
        if not code.startswith("2"):
            continue
        media = ((response or {}).get("content") or {}).get("application/json") or {}
        schema = media.get("schema") or {}
        ref = schema.get("$ref") or ((schema.get("allOf") or [{}])[0]).get("$ref")
        if ref:
            rust = types.get(_norm(ref.rsplit("/", 1)[-1]))
            success = f"crate::types::{rust}" if rust else "serde_json::Value"
        elif media:
            success = "serde_json::Value"
        break

    url_args = "".join(f", progenitor_client::encode_path({_ident(p)})" for p in path_params)
    url = re.sub(r"\{[^}]+\}", "{}", path)
    ok = (
        "crate::ResponseValue::from_response(response).await"
        if success != "()"
        else "Ok(crate::ResponseValue::new((), status, response.headers().clone()))"
    )
    doc = _doc(op.get("summary") or "") + (["    ///"] if op.get("summary") and op.get("description") else [])
    doc += _doc(op.get("description") or "")
    doc += ["    ///", f"    /// Sends a `{method.upper()}` `multipart/form-data` request to `{path}`."]
    joined_args = ",\n        ".join(args)
    form_lines = "\n".join("    " + line for line in "\n".join(parts).splitlines())
    return f"""{chr(10).join(doc)}
    pub async fn {name}(
        {joined_args},
    ) -> Result<crate::ResponseValue<{success}>, crate::Error<serde_json::Value>> {{
        let url = format!("{{}}{url}", self.baseurl{url_args});
        #[allow(unused_mut)]
        let mut form = reqwest::multipart::Form::new();
{form_lines}
        let response = self
            .client
            .{method}(url)
            .header(reqwest::header::ACCEPT, "application/json")
            .multipart(form)
            .send()
            .await
            .map_err(crate::Error::CommunicationError)?;
        let status = response.status();
        if status.is_success() {{
            {ok}
        }} else if status.is_client_error() || status.is_server_error() {{
            Err(crate::Error::ErrorResponse(crate::ResponseValue::from_response(response).await?))
        }} else {{
            Err(crate::Error::UnexpectedResponse(response))
        }}
    }}
"""


def render_multipart(spec: dict, lib_text: str) -> str | None:
    """``src/multipart.rs``: the operations progenitor cannot take, as methods on ``Client``; None if there are none."""
    schemas = spec.get("components", {}).get("schemas", {})
    types = _rust_types(lib_text)
    methods = []
    for path, item in (spec.get("paths") or {}).items():
        for method in _METHODS:
            op = item.get(method) if isinstance(item, dict) else None
            content = ((op or {}).get("requestBody") or {}).get("content") or {}
            if list(content) == ["multipart/form-data"]:
                methods.append(_render_multipart(path, method, op, schemas, types))
    if not methods:
        return None
    return (
        "// Code generated by django-cfg (openapi_processor.rust) — DO NOT EDIT.\n"
        "// progenitor takes no `multipart/form-data` body; these operations are written here, beside its client.\n\n"
        "impl crate::Client {\n" + "\n".join(methods) + "}\n"
    )


# ── Cargo.toml ───────────────────────────────────────────────────────

#: ``[workspace.package]`` keys a member inherits when the workspace defines them.
_INHERITABLE = ("version", "edition", "rust-version", "publish", "license", "authors", "repository", "homepage")

#: progenitor builds reqwest without TLS; the crate offers the three ways to get HTTPS.
_TLS_FEATURES = (
    'default-tls = ["reqwest/default-tls"]\n'
    'rustls-no-provider = ["reqwest/rustls-no-provider"]\n'
    'native-tls = ["reqwest/native-tls"]\n'
)

#: Standalone: HTTPS works out of the box (reqwest's rustls on aws-lc-rs).
_FEATURES_STANDALONE = (
    "\n[features]\n"
    "# HTTPS: progenitor builds reqwest without TLS. `default-tls` is reqwest's rustls on aws-lc-rs.\n"
    "# With `default-features = false` pick `native-tls`, or `rustls-no-provider` and install a rustls\n"
    "# CryptoProvider (ring or aws-lc-rs) before building the client.\n"
    'default = ["default-tls"]\n' + _TLS_FEATURES
)

#: Workspace member: the TLS stack is the workspace's policy, so nothing is on by default.
_FEATURES_WORKSPACE = (
    "\n[features]\n"
    "# HTTPS is the consumer's choice: enable one feature. `rustls-no-provider` brings no crypto backend:\n"
    "# call `rustls::crypto::ring::default_provider().install_default()` before building the client.\n"
    "default = []\n" + _TLS_FEATURES
)

#: First line of ``lib.rs``: the code is progenitor's, a workspace's lints judge the schema, not it.
_LINT_ALLOW = (
    "#![allow(\n"
    "    clippy::all,\n    clippy::pedantic,\n    clippy::nursery,\n    clippy::restriction,\n    clippy::cargo,\n"
    "    missing_docs,\n    missing_debug_implementations,\n    unreachable_pub,\n    unused_qualifications,\n"
    '    reason = "generated by progenitor and django-cfg: fix the Django schema, then `make gen`"\n'
    ")]\n"
)


def _toml(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, list):
        return "[" + ", ".join(_toml(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{k} = {_toml(v)}" for k, v in value.items()) + " }"
    return str(value)


def unstaged_dir(path: Path) -> Path:
    from ....pipeline.runner.cache_keys import unstaged

    return unstaged(path)


def find_workspace_root(start: Path) -> Path | None:
    """The nearest ``Cargo.toml`` above ``start`` that declares ``[workspace]``."""
    for folder in [Path(start), *Path(start).parents]:
        cargo = folder / "Cargo.toml"
        if cargo.is_file():
            try:
                if "workspace" in tomllib.loads(cargo.read_text(encoding="utf-8")):
                    return folder
            except (OSError, tomllib.TOMLDecodeError):
                continue
    return None


def _unused_deps(out_dir: Path, deps: dict) -> list[str]:
    """Dependencies no source file names (cargo-machete would flag them): ``regress`` when no field has a pattern."""
    source = "\n".join(p.read_text(encoding="utf-8") for p in sorted((out_dir / "src").glob("*.rs")))
    return [name for name in deps if not re.search(rf"\b{re.escape(name.replace('-', '_'))}::", source)]


def write_cargo(out_dir: Path, *, multipart: bool, workspace_root: Path | None = None) -> list[str]:
    """Rewrite progenitor's ``Cargo.toml``. Returns the dependencies the workspace still has to declare.

    Standalone: the versions progenitor chose, plus the multipart and TLS features (``default-tls`` on).
    With ``workspace_root`` the crate is a member: inherited package keys,
    ``dep = { workspace = true, features = [...] }``, ``[lints] workspace = true``, no TLS by default
    (the consumer picks), and ``workspace-dependencies.toml`` with the entries for the root.
    """
    cargo = out_dir / "Cargo.toml"
    manifest = tomllib.loads(cargo.read_text(encoding="utf-8"))
    package = manifest.get("package", {})
    deps: dict = {}
    for name, spec in (manifest.get("dependencies") or {}).items():
        spec = {"version": spec} if isinstance(spec, str) else dict(spec)
        if name == "reqwest" and multipart:
            spec["features"] = list(dict.fromkeys([*spec.get("features", []), "multipart"]))
        deps[name] = spec

    lines = ["# Generated by django-cfg (progenitor) — DO NOT EDIT. Regenerated on every `make gen`.", "", "[package]"]
    lines.append(f"name = {_toml(package['name'])}")
    missing: list[str] = []
    if workspace_root is not None:
        root = tomllib.loads((workspace_root / "Cargo.toml").read_text(encoding="utf-8"))
        shared = root.get("workspace", {}).get("package", {})
        for key in _INHERITABLE:
            if key in shared:
                lines.append(f"{key}.workspace = true")
            elif key in package:
                lines.append(f"{key} = {_toml(package[key])}")
        declared = root.get("workspace", {}).get("dependencies", {})
        lines += ["", "[dependencies]"]
        fragment = [
            "# Entries for [workspace.dependencies] in "
            f"{Path(os.path.relpath(workspace_root / 'Cargo.toml', unstaged_dir(out_dir))).as_posix()}: "
            "the versions progenitor needs.",
            "# Generated by django-cfg; features are set by the member crate (they are additive).",
        ]
        for name, spec in deps.items():
            member = {"workspace": True, **({"features": spec["features"]} if spec.get("features") else {})}
            lines.append(f"{name} = {_toml(member)}")
            root_spec = {k: v for k, v in spec.items() if k != "features"}
            fragment.append(f"{name} = {_toml(root_spec)}")
            if name not in declared:
                missing.append(name)
        (out_dir / "workspace-dependencies.toml").write_text("\n".join(fragment) + "\n", encoding="utf-8")
    else:
        for key in ("version", "edition", "license"):
            if key in package:
                lines.append(f"{key} = {_toml(package[key])}")
        lines += ["", "[dependencies]"]
        lines += [f"{name} = {_toml(spec)}" for name, spec in deps.items()]

    unused = _unused_deps(out_dir, deps)
    if unused:
        lines += ["", "[package.metadata.cargo-machete]", f"ignored = {_toml(unused)}"]
    text = "\n".join(lines) + "\n" + (_FEATURES_STANDALONE if workspace_root is None else _FEATURES_WORKSPACE)
    if workspace_root is not None:
        text += "\n[lints]\nworkspace = true\n"
    cargo.write_text(text, encoding="utf-8")
    return missing


# ── rustfmt ──────────────────────────────────────────────────────────

#: Files rustfmt reads besides the sources: the config and the pinned toolchain (``cargo fmt`` honours both).
_FMT_CONFIGS = ("rustfmt.toml", ".rustfmt.toml", "rust-toolchain.toml", "rust-toolchain")


def find_rustfmt() -> str | None:
    found = shutil.which("rustfmt")
    if found:
        return found
    home = Path(os.environ.get("CARGO_HOME") or Path.home() / ".cargo") / "bin" / "rustfmt"
    return str(home) if home.is_file() else None


def rustfmt_version(cwd: Path) -> str:
    """``rustfmt --version`` where the crate lives: rustup's proxy resolves the pinned toolchain from ``cwd``."""
    rustfmt = find_rustfmt()
    if rustfmt is None:
        return "missing"
    folder = next((f for f in [Path(cwd), *Path(cwd).parents] if f.is_dir()), Path.cwd())
    try:
        out = subprocess.run(  # noqa: S603 — rustfmt from PATH, version only
            [rustfmt, "--version"], cwd=folder, capture_output=True, text=True, check=False, timeout=30
        )
    except (OSError, subprocess.TimeoutExpired):
        return "unavailable"
    return out.stdout.strip() or out.stderr.strip()[:200]


def rustfmt_inputs(start: Path) -> bytes:
    """Every rustfmt config and toolchain file from ``start`` up: what makes ``cargo fmt`` format differently."""
    h = []
    for folder in [Path(start), *Path(start).parents]:
        for name in _FMT_CONFIGS:
            path = folder / name
            if path.is_file():
                h.append(path.relative_to(folder).as_posix().encode() + b"\x00" + path.read_bytes())
    return b"\x01".join(h)


def _edition(out_dir: Path, workspace_root: Path | None) -> str:
    package = tomllib.loads((out_dir / "Cargo.toml").read_text(encoding="utf-8")).get("package", {})
    edition = package.get("edition")
    if isinstance(edition, dict) and workspace_root is not None:
        root = tomllib.loads((workspace_root / "Cargo.toml").read_text(encoding="utf-8"))
        edition = root.get("workspace", {}).get("package", {}).get("edition")
    return edition if isinstance(edition, str) else "2021"


def format_crate(out_dir: Path, workspace_root: Path | None = None) -> bool:
    """``rustfmt --edition <crate's>`` over ``src/*.rs``, as ``cargo fmt`` would: same output after a ``cargo fmt``.

    Runs inside the crate folder, so rustup picks the workspace's ``rust-toolchain.toml`` and rustfmt the
    nearest ``rustfmt.toml`` above it. A missing or failing rustfmt is a loud warning, not an error: the
    crate still builds, it is only unformatted.
    """
    files = sorted(str(p) for p in (out_dir / "src").glob("*.rs"))
    if not files:
        return True
    rustfmt = find_rustfmt()
    if rustfmt is None:
        print(
            f"! rustfmt not found: {out_dir} is written unformatted, so `cargo fmt` will change it. "
            "Install: rustup component add rustfmt",
            file=sys.stderr,
        )
        return False
    edition = _edition(out_dir, workspace_root)
    result = subprocess.run(  # noqa: S603 — rustfmt from PATH on our own generated files
        [rustfmt, "--edition", edition, *files], cwd=out_dir, capture_output=True, text=True, check=False
    )
    if result.returncode != 0:
        print(f"! rustfmt failed on {out_dir} (left unformatted): {result.stderr.strip()[:500]}", file=sys.stderr)
        return False
    return True


def generate(out_dir: Path, spec_path: Path | None = None, *, workspace_root: Path | None = None) -> RustWrapperResult:
    """Write ``src/django.rs`` (and ``src/multipart.rs`` when needed), export them from ``src/lib.rs``, rewrite Cargo.toml.

    ``spec_path``: the sliced spec the crate was generated from; default ``<out_dir>/openapi.json``.
    ``workspace_root``: make the crate a member of that Cargo workspace (``Target.rust_workspace``).
    """
    lib = out_dir / "src" / "lib.rs"
    if not lib.is_file():
        return RustWrapperResult(out_dir=out_dir, skipped=True)

    module = out_dir / "src" / "django.rs"
    module.write_text(render(_crate_name(out_dir)), encoding="utf-8")
    written = [module, lib]

    text = lib.read_text(encoding="utf-8")
    spec_file = spec_path or out_dir / "openapi.json"
    spec = json.loads(spec_file.read_text(encoding="utf-8")) if spec_file.is_file() else {}
    multipart = render_multipart(spec, text)
    if multipart:
        (out_dir / "src" / "multipart.rs").write_text(multipart, encoding="utf-8")
        written.append(out_dir / "src" / "multipart.rs")

    if _LIB_MARKER not in text:
        text = text.rstrip("\n") + (
            f"\n\n{_LIB_MARKER}\npub mod django;\npub use django::{{DjangoClientBuilder, DjangoClientError}};\n"
            "/// The `reqwest` this crate is built on: build a `multipart::Part` or a header with it.\npub use reqwest;\n"
            + ("mod multipart;\n" if multipart else "")
        )
        lib.write_text(text, encoding="utf-8")
    if not text.startswith(_LINT_ALLOW):
        lib.write_text(_LINT_ALLOW + "\n" + lib.read_text(encoding="utf-8"), encoding="utf-8")
    missing = write_cargo(out_dir, multipart=bool(multipart), workspace_root=workspace_root)
    (out_dir / ".gitignore").write_text("/target\nCargo.lock\n", encoding="utf-8")
    written += [out_dir / "Cargo.toml", out_dir / ".gitignore"]
    formatted = format_crate(out_dir, workspace_root)
    return RustWrapperResult(out_dir=out_dir, written=written, missing_workspace_deps=missing, formatted=formatted)
