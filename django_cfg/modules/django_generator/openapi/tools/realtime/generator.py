"""Typed realtime topics (``realtime.ts``) from the ``x-realtime`` extension.

One builder per declared topic pattern, named after its literal parts: ``orders:{order_id:int}`` becomes
``ordersTopic({ orderId })``, ``demo.ping`` becomes ``demoPingTopic()``. A builder returns a ``RealtimeTopic<E>``:
the concrete name the client puts in ``sub``, the pattern, whether visitors may subscribe, and the zod schema of
``msg.data`` (from Orval's generated model tree). The type is structural, so the
``@djangocfg/realtime`` client accepts it without this file importing that package.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from .topic_patterns import split_pattern

REALTIME_FILE = "realtime.ts"

_WORD_RE = re.compile(r"[._\-]+")

_HEADER = """// AUTO-GENERATED by django_cfg realtime adapter
// Typed realtime topics (django_realtime, wire protocol v1). DO NOT EDIT — re-run `make gen`.
//
//   useTopic(ordersTopic({ orderId: 42 }), (event) => { ... })   // event is typed and validated
//
// `name` is what the client sends in `sub`; `schema` validates `msg.data`.
"""

_RUNTIME = """/** A subscribable topic. `__event` only carries the event type for inference; it is never set. */
export interface RealtimeTopic<TEvent> {
  readonly name: string;
  readonly pattern: string;
  readonly anonymous: boolean;
  readonly schema: z.ZodType<TEvent> | null;
  readonly __event?: TEvent;
}

export const REALTIME_PATH = %(path)s;
export const REALTIME_PROTOCOL = %(version)d;

const SEGMENT: Record<'str' | 'int', RegExp> = { str: /^[A-Za-z0-9_.-]+$/, int: /^-?[0-9]+$/ };

function segment(pattern: string, name: string, kind: 'str' | 'int', value: string | number): string {
  const text = String(value);
  if (!SEGMENT[kind].test(text)) {
    throw new Error(`realtime topic ${pattern}: ${name}=${text} is not a valid ${kind} segment`);
  }
  return text;
}
"""


class RealtimeCodegenError(ValueError):
    pass


def _camel(snake: str) -> str:
    head, *rest = [p for p in _WORD_RE.split(snake) if p]
    return head.lower() + "".join(p[:1].upper() + p[1:] for p in rest)


def _pascal(text: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in _WORD_RE.split(text) if p)


def _segments(pattern: str) -> list:
    """[(literal, None) | (param_name, kind)] after the base."""
    return split_pattern(pattern)[1]


def _base(pattern: str) -> str:
    return split_pattern(pattern)[0]


def _doc(text: str) -> str:
    """Text safe inside a /** */ comment."""
    return text.replace("*/", "*\\/")


def _builder_names(topics: list[dict]) -> list[str]:
    names = []
    for topic in topics:
        pattern = topic["name"]
        base = _base(pattern)
        literals = "".join(_pascal(text) for text, kind in _segments(pattern) if kind is None)
        names.append(_camel(base) + literals + "Topic")
    for index, name in enumerate(names):
        if names.count(name) > 1:
            params = "And".join(_pascal(p) for p, kind in _segments(topics[index]["name"]) if kind)
            names[index] = name.removesuffix("Topic") + ("By" + params if params else "") + "Topic"
    duplicates = sorted({n for n in names if names.count(n) > 1})
    if duplicates:
        raise RealtimeCodegenError(f"realtime topics map to the same builder name: {', '.join(duplicates)}")
    return names


def _event_name(topic: dict) -> str:
    ref = (topic.get("event") or {}).get("$ref", "")
    return ref.rsplit("/", 1)[-1] if ref.startswith("#/components/schemas/") else ""


def _model_file(name: str) -> str:
    """Return Orval's deterministic lower-camel Zod model filename."""
    return name[:1].lower() + name[1:] if name else ""


def _render_topic(topic: dict, fn: str, *, with_zod: bool) -> str:
    pattern = topic["name"]
    event = _event_name(topic) if with_zod else ""
    event_type = f"{event}Output" if event else "unknown"
    schema = f"{event}" if event else "null"
    params = [(name, kind) for name, kind in _segments(pattern) if kind]
    parts = [_base(pattern)]
    for name, kind in _segments(pattern):
        if kind is None:
            parts.append(name)
        else:
            parts.append("${segment(PATTERN, %s, %s, params.%s)}" % (
                json.dumps(_camel(name)), json.dumps(kind), _camel(name)))
    template = ":".join(parts).replace("PATTERN", json.dumps(pattern))
    signature = ""
    if params:
        fields = "; ".join(f"{_camel(n)}: {'number' if k == 'int' else 'string'}" for n, k in params)
        signature = f"params: {{ {fields} }}"
    doc = _doc(topic.get("description") or "")
    access = "visitors and users" if topic.get("anonymous") else "signed-in users"
    return f"""
/** `{pattern}` ({access}, history {topic.get('history', '?')}).{' ' + doc if doc else ''} */
export function {fn}({signature}): RealtimeTopic<{event_type}> {{
  return {{
    name: `{template}`,
    pattern: {json.dumps(pattern)},
    anonymous: {'true' if topic.get('anonymous') else 'false'},
    schema: {schema},
  }};
}}
"""


def render_realtime(
    document: dict,
    *,
    with_zod: bool = True,
    model_import: str = "./models",
) -> str:
    topics = sorted(document.get("topics") or [], key=lambda t: t["name"])
    names = _builder_names(topics)
    events = sorted({_event_name(t) for t in topics if _event_name(t)}) if with_zod else []
    lines = [_HEADER, "import type { z } from 'zod';"]
    for event in events:
        lines.append(
            f"import {{ {event}, type {event}Output }} from "
            f"{json.dumps(f'{model_import}/{_model_file(event)}.zod')}"
        )
    lines.append("")
    lines.append(_RUNTIME % {"path": json.dumps(document.get("path") or "/ws"), "version": int(document.get("version", 1))})
    lines.extend(_render_topic(t, fn, with_zod=with_zod) for t, fn in zip(topics, names))
    index: dict[str, Any] = {
        t["name"]: {"builder": fn, "anonymous": bool(t.get("anonymous")), "history": t.get("history"),
                    "params": [p["name"] for p in t.get("params") or []]}
        for t, fn in zip(topics, names)
    }
    lines.append(f"\n/** Every topic of this group, by pattern. */\nexport const realtimeTopics = {json.dumps(index, indent=2)} as const;\n")
    return "\n".join(lines)


def generate_realtime(
    document: Any,
    out_dir: Path,
    *,
    with_zod: bool = True,
    model_import: str = "./models",
) -> list[Path]:
    """Write ``out_dir/realtime.ts`` beside Orval's generated model tree."""
    path = out_dir / REALTIME_FILE
    if not isinstance(document, dict) or not document.get("topics"):
        path.unlink(missing_ok=True)
        return []
    out_dir.mkdir(parents=True, exist_ok=True)
    path.write_text(
        render_realtime(document, with_zod=with_zod, model_import=model_import),
        encoding="utf-8",
    )
    return [path]


__all__ = ["REALTIME_FILE", "RealtimeCodegenError", "generate_realtime", "render_realtime"]
