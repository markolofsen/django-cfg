const MenubarItem = React.forwardRef<
  React.ElementRef<typeof MenubarPrimitive.Item>,
  React.ComponentPropsWithoutRef<typeof MenubarPrimitive.Item> & {
    inset?: boolean
    href?: string
    /** Visual style. `destructive` paints the row red on focus. */
    variant?: "default" | "destructive"
    key?: React.Key
  }
>(({ className, inset, href, variant = "default", children, ...props }, ref) => {
  const classes = cn(
    "relative flex cursor-default select-none items-center rounded-[var(--radius-sm)] px-(--menu-item-px) py-(--menu-item-py) text-(length:--menu-font-size) outline-none focus:bg-accent focus:text-accent-foreground data-[disabled]:pointer-events-none data-[disabled]:opacity-50",
    "data-[variant=destructive]:text-destructive data-[variant=destructive]:focus:bg-destructive/10 data-[variant=destructive]:focus:text-destructive",
    inset && "pl-8",
    className
  )

  if (href) {
    return (
      <MenubarPrimitive.Item asChild ref={ref} data-variant={variant} {...props}>
        <Link href={href} className={classes}>
          {children}
        </Link>
      </MenubarPrimitive.Item>
    )
  }

  return (
    <MenubarPrimitive.Item
      ref={ref}
      data-variant={variant}
      className={classes}
      {...props}
    >
      {children}
    </MenubarPrimitive.Item>
  )
})
MenubarItem.displayName = MenubarPrimitive.Item.displayName

