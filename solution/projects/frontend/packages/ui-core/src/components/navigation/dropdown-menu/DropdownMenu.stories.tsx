function CheckboxesDemo() {
  const [bars, setBars] = useState({ status: true, activity: false, panel: false });
  return (
    <DropdownMenu>
      <DropdownMenuTrigger asChild>
        <Button variant="outline">View Options</Button>
      </DropdownMenuTrigger>
      <DropdownMenuContent className="w-56">
        <DropdownMenuLabel>Appearance</DropdownMenuLabel>
        <DropdownMenuSeparator />
        <DropdownMenuCheckboxItem
          checked={bars.status}
          onCheckedChange={(c) => setBars({ ...bars, status: !!c })}
        >
          Status Bar
        </DropdownMenuCheckboxItem>
        <DropdownMenuCheckboxItem
          checked={bars.activity}
          onCheckedChange={(c) => setBars({ ...bars, activity: !!c })}
        >
          Activity Bar
        </DropdownMenuCheckboxItem>
        <DropdownMenuCheckboxItem
          checked={bars.panel}
          onCheckedChange={(c) => setBars({ ...bars, panel: !!c })}
        >
          Panel
        </DropdownMenuCheckboxItem>
      </DropdownMenuContent>
    </DropdownMenu>
  );
}

export const WithCheckboxes: Story = { render: () => <CheckboxesDemo /> };

